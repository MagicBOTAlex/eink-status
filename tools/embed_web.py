#!/usr/bin/env python3
"""Embed the built web UI into the firmware as C arrays.

Run by `npm run build` in web/, or manually after editing web/index.html or the
Tailwind output:

    python3 tools/embed_web.py
"""

from __future__ import annotations

import pathlib

DUMP_COLUMNS = 16


def emit(out, name: str, path: pathlib.Path) -> None:
    data = path.read_bytes()
    out.write("const char %s[] = {\n" % name)
    for offset in range(0, len(data), DUMP_COLUMNS):
        chunk = data[offset : offset + DUMP_COLUMNS]
        out.write("    " + " ".join("0x%02X," % b for b in chunk) + "\n")
    out.write("};\n")
    out.write("const size_t %sSize = sizeof(%s);\n\n" % (name, name))


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    web = root / "web"

    index = web / "index.html"
    css = web / "app.css"
    for path in (index, css):
        if not path.exists():
            print("missing web asset: %s (run the Tailwind build first)" % path)
            return 1

    target = root / "src/web/assets.cpp"
    target.parent.mkdir(parents=True, exist_ok=True)

    with target.open("w") as out:
        out.write("// Generated by tools/embed_web.py -- do not edit.\n")
        out.write('#include "web/assets.hpp"\n\n')
        out.write("namespace web {\n\n")
        emit(out, "kIndexHtml", index)
        emit(out, "kAppCss", css)
        out.write("} // namespace web\n")

    print("embedded %s (%d B) and %s (%d B) -> %s"
          % (index.name, index.stat().st_size, css.name, css.stat().st_size,
             target.relative_to(root)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
