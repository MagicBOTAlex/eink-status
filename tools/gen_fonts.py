#!/usr/bin/env python3
"""Generate compact 1 bpp font tables for the ui::Font renderer.

The device and the host preview/test builds link the exact same tables, so a
layout that passes the test suite renders identically on the panel.

Usage:
    python3 tools/gen_fonts.py CozetteVector-nerd.ttf src/ui/fonts

Only printable ASCII and the Danish letters used by the UI are included:
U+0020..U+007E plus AE, OE, AA (upper and lower case).
"""

from __future__ import annotations

import os
import sys

from PIL import ImageFont

# Cozette is a pixel font; these sizes give integer-ish stems.
SIZES = [16, 96]

CHARS = [chr(c) for c in range(0x20, 0x7F)] + list("\u00c6\u00d8\u00c5\u00e6\u00f8\u00e5")


def glyph_name(ch: str) -> str:
    return "U+%04X" % ord(ch)


def generate(ttf: str, size: int, ident: str, symbol: str, out_dir: str) -> None:
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()

    glyphs = []
    blob = bytearray()
    for ch in CHARS:
        advance = int(round(font.getlength(ch)))
        mask, (ox, oy) = font.getmask2(ch, mode="1")
        w, h = mask.size
        if w and h:
            offset = len(blob)
            # pack rows MSB-first, 1 byte per row
            stride = (w + 7) // 8
            data = bytearray(stride * h)
            for y in range(h):
                for x in range(w):
                    if mask.getpixel((x, y)) > 127:
                        data[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
            blob.extend(data)
        else:
            offset = 0
        # The renderer stores these in fixed-width fields; fail loudly rather
        # than emitting a cryptic narrowing error in C++.
        assert 0 <= w <= 255 and 0 <= h <= 255, "glyph %r is too wide/tall" % ch
        assert -128 <= ox <= 127 and -128 <= oy <= 127, "glyph %r offset" % ch
        assert 0 <= advance <= 255, "glyph %r advance" % ch
        assert len(blob) <= 0xFFFF, "glyph table exceeds 16-bit offsets"
        glyphs.append((ord(ch), w, h, ox, oy, advance, offset))

    header = os.path.join(out_dir, ident + ".hpp")
    source = os.path.join(out_dir, ident + ".cpp")

    with open(header, "w") as f:
        f.write("// Generated by tools/gen_fonts.py -- do not edit.\n")
        f.write("#pragma once\n\n#include \"ui/font.hpp\"\n\n")
        f.write("namespace ui::fonts {\n\n")
        f.write("extern const Glyph k%sGlyphs[];\n" % symbol)
        f.write("extern const uint8_t k%sBitmap[];\n" % symbol)
        f.write("extern const Font k%s;\n\n" % symbol)
        f.write("} // namespace ui::fonts\n")

    with open(source, "w") as f:
        f.write("// Generated by tools/gen_fonts.py -- do not edit.\n")
        f.write("#include \"ui/fonts/%s.hpp\"\n\n" % ident)
        f.write("namespace ui::fonts {\n\n")
        f.write("const Glyph k%sGlyphs[] = {\n" % symbol)
        for cp, w, h, ox, oy, adv, off in glyphs:
            # A bare backslash would turn the trailing comment into a line
            # continuation, which -Werror rejects.
            label = "backslash" if cp == 0x5C else chr(cp)
            f.write("    {0x%04X, %d, %d, %d, %d, %d, %d}, // %s\n"
                    % (cp, w, h, ox, oy, adv, off, label))
        f.write("};\n\n")
        f.write("const uint8_t k%sBitmap[] = {\n" % symbol)
        for i in range(0, len(blob), 16):
            f.write("    " + " ".join("0x%02X," % b for b in blob[i:i + 16]) + "\n")
        f.write("};\n\n")
        f.write("const Font k%s = {\"%s\", %d, %d, %d, %d, k%sGlyphs, %d, k%sBitmap};\n\n"
                % (symbol, ident, ascent + descent, ascent, descent, size,
                   symbol, len(glyphs), symbol))
        f.write("} // namespace ui::fonts\n")

    used = sum(1 for g in glyphs if g[1] and g[2])
    overhang = sum(1 for g in glyphs if g[1] and g[3] + g[1] > g[5])
    print("%-24s size=%3d glyphs=%3d ink=%3d overhang=%2d bytes=%6d -> %s"
          % (ident, size, len(glyphs), used, overhang, len(blob), source))
    if overhang:
        print("  note: %d glyph(s) paint past their advance; measurement uses "
              "the ink extent, so this is handled" % overhang)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    ttf, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    for size in SIZES:
        generate(ttf, size, "cozette_%d" % size, "Cozette%d" % size, out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
